"""Additive power-only recovery of a strict checkpoint NAME/TOP guard.

Default prepares a certificate only. --run is root-owned and launches exactly
one annotation/power job using the unchanged accepted energy_a0 replay.
"""
from pathlib import Path
from types import SimpleNamespace
import argparse
import hashlib
import importlib.util
import json
import re
import sys
import xml.etree.ElementTree as ET
import zipfile

sys.dont_write_bytecode = True
P = Path(__file__).resolve().parent
TOP = "top_sequential_leak16_glif_mcm"
PART = "xc7a100tcsg324-1"
DCP_SHA = "27fb1a4104e6b369dcef444db8939c81e1ec6fef95a6f168bd326faaf8f70347"
ORIGINAL_RUNNER_SHA = ""  # Checked through immutable replay/preparation stamps below.
ORIGINAL_TCL_SHA = "5e4052e242fdbf1210042e9b71462417f72add61fab0a53b0356d740e6c053b8"
ORIGINAL_AUDITOR_SHA = "6db1e41a3f0f833fac90ee9ca00aca53c5c0bdd15a998799ac2e252b494eee03"
RD = P / "hardware/route12_a0"
RP = P / "hardware/replay12_glif_mcm_energy_a0"
RAW = P / "hardware/export_raw12_glif_mcm_energy_a0"
OLD_PROGRESS = P / "energy_energy_a0_golden_export_replay_power_progress.json"
CERT = P / "power_recovery_identity_certificate_v1.json"
WD = P / "hardware/power12_glif_mcm_energy_recovery_a0"
PROGRESS = P / "energy_recovery_a0_power_progress.json"
NEW_TCL = P / "power_energy_glif_mcm_recovery_v1.tcl"


def sha(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as f:
        for block in iter(lambda: f.read(1048576), b""):
            h.update(block)
    return h.hexdigest()


def load_module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def inputs():
    # Import the original memory/telemetry policy without changing it.
    runner = load_module("glif_mcm_frozen_budget_recovery", P / "run_energy_glif_mcm_budget_v1.py")
    runner.ARGS = SimpleNamespace(
        native_acceptance=P / "hardware/native_actual_glif_s0_a0/acceptance.json",
        route_directory=RD,
        attempt="energy_a0",
    )
    b = runner.b
    sources = runner.sources()
    rd, hardware = runner.route()
    assert rd == RD and hardware["top"] == TOP
    dcp = RD / "design.dcp"
    assert sha(dcp) == DCP_SHA
    assert hardware["artifact_sha256"][str(dcp)] == DCP_SHA
    replay = b.read(RP / "replay_checks.json")
    assert replay["status"] == "timing_pass_activity_pending"
    assert replay["engine"] == 9 and replay["design_top"] == TOP
    b.verify(replay["source_sha256"])
    b.verify(replay["artifact_sha256"])
    assert replay["source_sha256"][str(dcp)] == DCP_SHA
    old = b.read(OLD_PROGRESS)
    assert old["status"] == "completed_with_retained_failures"
    assert old["stages"] == ["golden", "export", "replay"]
    assert len(old["failures"]) == 1
    assert old["failures"][0]["stage"] == "power"
    assert "Shared GLIF MCM top mismatch" in old["failures"][0]["reason"]
    b.verify(old["source_sha256"])

    original_tcl = P / "power_energy_glif_mcm.tcl"
    assert sha(original_tcl) == ORIGINAL_TCL_SHA
    prior_guard = 'if {[get_property NAME [current_design]] ne "top_sequential_leak16_glif_mcm"} {error "Shared GLIF MCM top mismatch"}'
    corrected_guard = 'if {[get_property NAME [current_design]] ne "checkpoint_design" || [get_property TOP [current_design]] ne "top_sequential_leak16_glif_mcm"} {error "Shared GLIF MCM top mismatch"}'
    before = original_tcl.read_text()
    after = NEW_TCL.read_text()
    assert before.count(prior_guard) == 1
    assert after == before.replace(prior_guard, corrected_guard, 1), "Only the one identity guard may change."
    assert sha(P / "audit_energy_glif_mcm.py") == ORIGINAL_AUDITOR_SHA

    with zipfile.ZipFile(dcp) as z:
        dcp_xml = z.read("dcp.xml")
    root = ET.fromstring(dcp_xml)
    xml_identity = {key: root.find(key).attrib["Name"] for key in ("Top", "Part")}
    assert xml_identity == {"Top": TOP, "Part": PART}
    properties_file = RAW / "design_properties.rpt"
    properties_text = properties_file.read_text()
    properties = {}
    for key in ("NAME", "TOP", "PART"):
        match = re.search(r"^" + key + r"\s+\S+\s+\S+\s+(.+)$", properties_text, re.M)
        assert match, key
        properties[key] = match[1].strip()
    assert properties == {"NAME": "checkpoint_design", "TOP": TOP, "PART": PART}
    raw_provenance = b.read(RAW / "provenance.json")
    b.verify(raw_provenance)
    assert raw_provenance[str(dcp)] == DCP_SHA
    raw_artifacts = b.read(RAW / "artifacts.json")
    b.verify(raw_artifacts)
    # The properties report was generated by the same recorded export job.
    export_job = b.read(RAW / "export.job.json")
    assert export_job["returncode"] == 0
    assert str(dcp).replace("\\", "/") in export_job["argv"]

    named = RP / "activity_named.saif"
    names = named.with_suffix(".names.json")
    normalization = b.read(names)
    assert normalization["target_sha256"] == sha(named)
    assert normalization["source_sha256"] == sha(RP / "activity.saif")
    auditor = load_module("glif_mcm_original_strict_recovery_auditor", P / "audit_energy_glif_mcm.py")
    strict_replay = auditor.replay(RP)
    assert strict_replay["status"] == "pass" and strict_replay["scalar_updates"] == 262528
    pins = sources | b.pins([
        Path(__file__), NEW_TCL, original_tcl, P / "audit_energy_glif_mcm.py",
        OLD_PROGRESS, P / "run_energy_glif_mcm_budget_v1.py",
        dcp, RD / "hardware.json", properties_file,
        RAW / "provenance.json", RAW / "artifacts.json", RAW / "export.job.json",
        RP / "replay_checks.json", named, names,
        P / "hardware/power12_glif_mcm_energy_a0/annotation.log",
    ])
    certificate = dict(
        status="prepared_power_only_identity_guard_recovery_no_energy_acceptance",
        original_failure_file=str(OLD_PROGRESS), retained_original_stages=old["stages"],
        original_failure="NAME compared with HDL TOP; no power reports accepted",
        original_tcl_sha256=ORIGINAL_TCL_SHA, corrected_tcl_sha256=sha(NEW_TCL),
        one_guard_replacement=True, previous_guard=prior_guard, corrected_guard=corrected_guard,
        checkpoint_dcp_sha256=DCP_SHA, dcp_xml_sha256=hashlib.sha256(dcp_xml).hexdigest(),
        dcp_xml_identity=xml_identity, original_export_design_properties=properties,
        original_export_design_properties_file=str(properties_file),
        strict_reused_replay_audit=strict_replay, replay_dir=str(RP),
        new_power_directory=str(WD), original_auditor_sha256=ORIGINAL_AUDITOR_SHA,
        unchanged="Datapath, route/DCP, native/golden/export/replay, normalized SAIF, all other Tcl commands, part/clock/temperature, complete physical activity checks and original strict annotation auditor",
        source_sha256=pins,
    )
    if CERT.exists():
        assert b.read(CERT) == certificate, "Prepared recovery certificate changed."
    else:
        b.write(CERT, certificate)
    return runner, auditor, replay, pins | b.pins([CERT]), named


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run", action="store_true")
    args = ap.parse_args()
    runner, auditor, replay, stamps, named = inputs()
    b = runner.b
    if not args.run:
        print(json.dumps({"status": "prepared_no_vendor_launch", "certificate": str(CERT), "strict_replay": "pass", "power_directory": str(WD)}), flush=True)
        return
    assert not WD.exists() and not PROGRESS.exists(), "Preserve earlier recovery attempts."
    WD.mkdir(parents=True)
    state = dict(status="running_power_only_recovery", engine=9, B=16,
                 replay_reused=str(RP), accepted_energy=False, source_sha256=stamps)
    b.write(PROGRESS, state)
    b.write(WD / "provenance.json", stamps)
    try:
        runner.tool([
            b.VIVADO / "bin/vivado.bat", "-mode", "batch", "-log", "vivado.log",
            "-journal", "vivado.jou", "-source", NEW_TCL, "-tclargs",
            9, RD / "design.dcp", named, WD,
        ], WD, "annotation", stamps, 1.6)
        b.write(WD / "evidence.json", dict(
            status="reports generated; independent audit required", B=16, engine=9,
            design_top=TOP, replay_dir=str(RP), hardware_file=str(RD / "hardware.json"),
            saif_file=str(named), source_sha256=stamps,
            artifact_sha256=b.pins(p for p in WD.iterdir() if p.is_file()),
            duration_seconds=replay["saif"]["duration_seconds"], neurons=replay["neurons"],
        ))
        audit = auditor.annotation(WD)
        assert audit["status"] == "pass"
        b.write(WD / "power_audit.json", audit)
        assert auditor.annotation(WD) == audit, "Independent annotation reproduction changed."
        b.verify(stamps)
        state.update(status="pass_power_only_recovery_original_strict_audit",
                     accepted_energy=True, power_audit_file=str(WD / "power_audit.json"),
                     power_audit_sha256=b.sha(WD / "power_audit.json"),
                     estimated_dynamic_energy_pJ_per_scalar_update=audit["estimated_dynamic_energy_pJ_per_scalar_update"])
    except Exception as exc:
        state.update(status="retained_power_only_recovery_failure", accepted_energy=False,
                     failure=repr(exc))
        b.write(PROGRESS, state)
        raise
    b.write(PROGRESS, state)
    print(json.dumps({k: state[k] for k in ("status", "accepted_energy", "estimated_dynamic_energy_pJ_per_scalar_update")}), flush=True)


if __name__ == "__main__":
    main()
